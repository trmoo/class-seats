function 비교실험() {
  // 회피 쪽은 후보를 수백 벌 만들어 보므로 학기 수를 줄인다.
  // 여기서는 후보 400벌만 쓴다 — 실제 [뽑기]는 1200벌이라 조금 더 잘 피한다.
  return { 무작위: 학기실험(false, 40), 회피: 학기실험(true, 40, 10, 400) };
}

function 비교결과보기(r) {
  const 줄 = (이름, 열쇠, 단위) => {
    const a = r.무작위[열쇠], b = r.회피[열쇠];
    const 준 = a > 0 ? Math.round((1 - b / a) * 100) : 0;
    return h('tr', {},
      h('td', {}, 이름),
      h('td', {}, a.toFixed(1) + 단위),
      h('td', {}, b.toFixed(1) + 단위),
      h('td', { style: { color: 준 > 0 ? 'var(--라임)' : 'var(--흐림)' } }, 준 > 0 ? `−${준}%` : '거의 같음'));
  };
  return h('div', {},
    h('table', { class: '표' },
      h('thead', {}, h('tr', {},
        h('th', {}, '한 학기에'), h('th', {}, '완전 무작위'), h('th', {}, '피하기 켬'), h('th', {}, '줄어든 정도'))),
      h('tbody', {},
        줄('2번 이상 짝이 된 조합', '짝2', '쌍'),
        줄('3번 이상 짝이 된 조합', '짝3', '쌍'),
        줄('같은 자리에 2번 이상', '자리2', '명'),
        줄('뒷줄에 5번 이상', '뒤5', '명'))),
    h('div', { class: '안내' },
      '가장 크게 줄어드는 것은 「3번 이상 같은 짝」입니다. 교실에서 실제로 불만이 나오는 것도 바로 그 경우입니다.'),
    h('div', { class: '안내 빨강' },
      '다만 피하기를 켜면 더 이상 균등한 무작위가 아닙니다. 모든 배치가 같은 확률로 나오지 않고, ' +
      '겹치지 않는 배치가 더 자주 나옵니다. 「공정」과 「골고루」는 서로 다른 것이라, ' +
      '무엇을 고를지는 선생님이 정하시면 됩니다.'),
    h('p', { class: '라벨' },
      '※ 이 실험은 빨리 끝내려고 후보를 400벌만 만들어 봅니다. ' +
      '실제 [뽑기]는 1200벌을 만들어 보므로 겹침이 이보다 조금 더 줄어듭니다.'),
  );
}

// ── 공통 ────────────────────────────────────────────────────
// 계산이 몇 초 걸리므로 "도는 중" 을 먼저 그린 뒤 다음 프레임에서 돌린다.
function 돌리기(이름, 일) {
  상태.도는중 = 이름;
  다시();
  setTimeout(() => {
    const 결과 = 일();
    if (이름 === '분포') 상태.분포결과 = 결과;
    if (이름 === '학기') 상태.학기결과 = 결과;
    if (이름 === '비교') 상태.비교결과 = 결과;
    상태.도는중 = null;
    다시();
  }, 30);
}

function 수치(이름, 값, 등급) {
  return h('div', { class: '수치 ' + 등급 },
    h('div', { class: '값' }, String(값)),
    h('div', { class: '이름' }, 이름));
}
