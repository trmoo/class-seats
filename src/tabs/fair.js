// 한 학기(10회 뽑기)를 여러 번 살아 보며 겹침을 센다.
function 학기실험(회피, 학기수 = 200, 회차 = 10, 시도 = 400) {
  const { 열, 행 } = 상태;
  const 총 = 열 * 행;
  const 번호들 = Array.from({ length: 총 }, (_, i) => i + 1);
  const 합 = { 짝2: 0, 짝3: 0, 자리2: 0, 뒤5: 0 };

  for (let e = 0; e < 학기수; e++) {
    const 이력 = [], 짝셈 = new Map(), 자리셈 = new Map(), 뒤셈 = new Map();
    for (let k = 0; k < 회차; k++) {
      const 배치 = 회피
        ? 회피배치(번호들, 열, 행, [], 이력, 시도).배치
        : 앉히기(섞기(번호들), 열, 행, []);
      for (const p of 짝목록(배치, 열, 행)) {
        const key = 짝열쇠(p);
        짝셈.set(key, (짝셈.get(key) || 0) + 1);
      }
      for (let s = 0; s < 배치.length; s++) {
        const n = 배치[s];
        if (n == null) continue;
        const 열쇠 = n + ':' + s;
        자리셈.set(열쇠, (자리셈.get(열쇠) || 0) + 1);
        if (구역(Math.floor(s / 열), 행) === '뒤') 뒤셈.set(n, (뒤셈.get(n) || 0) + 1);
      }
      이력.unshift({ 열, 행, 배치 });
      if (이력.length > 5) 이력.pop();
    }
    for (const [, v] of 짝셈) { if (v >= 2) 합.짝2++; if (v >= 3) 합.짝3++; }
    합.자리2 += new Set([...자리셈].filter(([, v]) => v >= 2).map(([k]) => k.split(':')[0])).size;
    합.뒤5 += [...뒤셈.values()].filter((v) => v >= 5).length;
  }
  return {
    짝2: 합.짝2 / 학기수, 짝3: 합.짝3 / 학기수,
    자리2: 합.자리2 / 학기수, 뒤5: 합.뒤5 / 학기수,
    인원: 총, 학기수, 회차,
  };
}

