function 분포실험() {
  const 총 = 상태.열 * 상태.행;
  const 번호들 = Array.from({ length: 총 }, (_, i) => i + 1);
  const 셈 = new Array(총).fill(0);
  for (let t = 0; t < 상태.횟수; t++) {
    const 배치 = 앉히기(섞기(번호들), 상태.열, 상태.행, []);
    셈[배치.indexOf(1)]++;
  }
  const 기대 = 상태.횟수 / 총;
  const chi2 = 셈.reduce((s, c) => s + (c - 기대) ** 2 / 기대, 0);
  const df = 총 - 1;
  const z = df > 0 ? (chi2 - df) / Math.sqrt(2 * df) : 0;
  return { 셈, 기대, chi2, df, z, 횟수: 상태.횟수, 열: 상태.열, 행: 상태.행 };
}

function 분포결과보기(r) {
  const 최소 = Math.min(...r.셈), 최대 = Math.max(...r.셈);
  const 고름 = Math.abs(r.z) < 1.96;
  const 히트 = h('div', {
    class: '히트맵',
    style: { gridTemplateColumns: `repeat(${r.열}, minmax(44px, 74px))` },
  });
  for (let i = 0; i < r.셈.length; i++) {
    // 기대값 대비 얼마나 높은지를 색 밝기로 (파랑 → 노랑)
    const 비 = r.기대 ? (r.셈[i] - 최소) / Math.max(1, 최대 - 최소) : 0;
    히트.appendChild(h('div', {
      class: '히트칸',
      style: { background: `color-mix(in srgb, #38bdf8 ${(1 - 비) * 100}%, #fbbf24)` },
      title: `${r.셈[i]}회`,
    }, String(r.셈[i])));
  }
  return h('div', {},
    히트,
    h('div', { class: '수치판', style: { marginTop: '14px' } },
      수치('가장 적은 자리', 최소.toLocaleString(), '보통'),
      수치('기대값', Math.round(r.기대).toLocaleString(), '보통'),
      수치('가장 많은 자리', 최대.toLocaleString(), '보통'),
      수치('치우침 z', r.z.toFixed(2), 고름 ? '좋음' : '나쁨'),
    ),
    h('div', { class: '안내 ' + (고름 ? '파랑' : '빨강') },
      고름
        ? `고릅니다. 카이제곱 ${r.chi2.toFixed(1)} (자유도 ${r.df}), z = ${r.z.toFixed(2)} 로 |z| < 1.96 안에 들어옵니다. 칸마다 숫자가 다른 것은 치우침이 아니라 흔들림입니다.`
        : `이번 결과는 |z| = ${Math.abs(r.z).toFixed(2)} 로 조금 벗어났습니다. 스무 번에 한 번은 이렇게 나옵니다 — 다시 돌려 보세요.`),
    h('details', { class: '더' },
      h('summary', {}, '🔬 카이제곱이 무엇인가요?'),
      h('div', {},
        h('p', {}, '칸마다 (실제 − 기대)² ÷ 기대 를 구해 모두 더한 값입니다. 고를수록 자유도(칸 수 − 1)에 가까워집니다.'),
        h('p', {}, 'z 는 그 값이 자유도에서 얼마나 떨어졌는지를 잰 것입니다. |z| < 1.96 이면 「고르다고 봐도 좋다」는 뜻입니다.'))),
  );
}

