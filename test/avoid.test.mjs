import { 벌점, 회피배치, 겹침요약, 가중치, 이력준비 } from '../src/core/avoid.js';
import { 앉히기, 짝목록, 짝열쇠, 구역표 } from '../src/core/seats.js';
import { 섞기 } from '../src/lib/random.js';
import { 묶음, 확인, 참 } from './harness.mjs';

const 열 = 5, 행 = 6, 총 = 30;
const 번호들 = Array.from({ length: 총 }, (_, i) => i + 1);
const 차례대로 = 앉히기(번호들, 열, 행, []);

묶음('벌점 셈하기');
확인('이력이 없으면 벌점 0', 벌점(차례대로, 열, 행, []), 0);
참('자기 자신과 견주면 벌점이 가장 크다',
  벌점(차례대로, 열, 행, [{ 열, 행, 배치: 차례대로 }]) > 벌점(앉히기(섞기(번호들), 열, 행, []), 열, 행, [{ 열, 행, 배치: 차례대로 }]));
{
  // 똑같은 배치를 다시 내면 짝 24쌍 + 자리 30 + 구역 30 이 모두 겹친다
  const 점 = 벌점(차례대로, 열, 행, [{ 열, 행, 배치: 차례대로 }]);
  확인('완전히 같은 배치의 벌점은 셈한 값과 맞는다',
    점, 24 * 가중치.짝 + 30 * 가중치.자리 + 30 * 가중치.구역);
}
참('오래된 이력일수록 가볍다', (() => {
  const 하나 = [{ 열, 행, 배치: 차례대로 }];
  const 둘 = [{ 열, 행, 배치: 앉히기(섞기(번호들), 열, 행, []) }, { 열, 행, 배치: 차례대로 }];
  // 같은 배치가 0번(무게 1)일 때보다 1번(무게 1/2)일 때 덜 아프다
  return 벌점(차례대로, 열, 행, 하나) > 벌점(차례대로, 열, 행, 둘) - 벌점(차례대로, 열, 행, [둘[0]]);
})());

묶음('겹침 요약');
{
  const 요약 = 겹침요약(차례대로, 열, 행, [{ 열, 행, 배치: 차례대로 }]);
  확인('같은 배치면 짝 24쌍이 겹친다', 요약.짝, 24);
  확인('같은 배치면 자리 30개가 겹친다', 요약.자리, 30);
  확인('같은 배치면 구역 30명이 겹친다', 요약.구역, 30);
  확인('이력이 없으면 이력없음 표시', 겹침요약(차례대로, 열, 행, []).이력없음, true);
}

묶음('회피 배치가 제대로 된 배치인가');
{
  const 이력 = [{ 열, 행, 배치: 차례대로 }];
  const { 배치 } = 회피배치(번호들, 열, 행, [], 이력, 200);
  확인('자리 수가 맞는다', 배치.length, 열 * 행);
  확인('1~30번이 한 번씩 들어 있다', [...배치].sort((a, b) => a - b), 번호들);
  const 없는자리 = [3, 7];
  const r2 = 회피배치(번호들.slice(0, 28), 열, 행, 없는자리, 이력, 200);
  확인('없는 자리는 null 로 남는다', 없는자리.map((i) => r2.배치[i]), [null, null]);
  확인('없는 자리를 뺀 만큼만 앉는다', r2.배치.filter((v) => v != null).length, 28);
}
확인('이력이 없으면 그냥 무작위라고 알려 준다', 회피배치(번호들, 열, 행, [], [], 50).이력없음, true);

묶음('회피가 실제로 겹침을 줄이는가');
{
  const 이력 = [{ 열, 행, 배치: 차례대로 }];
  let 무작위합 = 0, 회피합 = 0;
  const 횟수 = 40;
  for (let i = 0; i < 횟수; i++) {
    무작위합 += 겹침요약(앉히기(섞기(번호들), 열, 행, []), 열, 행, 이력).짝;
    회피합 += 겹침요약(회피배치(번호들, 열, 행, [], 이력, 400).배치, 열, 행, 이력).짝;
  }
  참(`회피 쪽 짝 겹침이 더 적다 (무작위 ${(무작위합 / 횟수).toFixed(2)} vs 회피 ${(회피합 / 횟수).toFixed(2)})`,
    회피합 < 무작위합);
  참('회피를 켜면 짝 겹침이 평균 1쌍 아래로 내려간다', 회피합 / 횟수 < 1);
}

묶음('★ 회피가 특정 번호를 계속 불리하게 만들지 않는가');
{
  // 이력을 굴려 가며 300번 뽑고, 번호마다 앞줄에 앉은 횟수를 센다.
  // 어떤 번호가 구조적으로 손해를 본다면 여기서 드러난다.
  const 뽑기수 = 300;
  const 앞셈 = new Map(번호들.map((n) => [n, 0]));
  const 이력 = [];
  for (let k = 0; k < 뽑기수; k++) {
    const { 배치 } = 회피배치(번호들, 열, 행, [], 이력, 300);
    const 표 = 구역표(배치, 열, 행);
    for (const n of 번호들) if (표[n] === '앞') 앞셈.set(n, 앞셈.get(n) + 1);
    이력.unshift({ 열, 행, 배치 });
    if (이력.length > 5) 이력.pop();
  }
  const 값 = [...앞셈.values()];
  const 최소 = Math.min(...값), 최대 = Math.max(...값);
  const 기대 = 뽑기수 / 3; // 앞·중·뒤 셋이므로 1/3
  참(`앞줄에 한 번도 못 앉는 번호가 없다 (최소 ${최소}회)`, 최소 > 기대 * 0.6);
  참(`앞줄을 독차지하는 번호도 없다 (최대 ${최대}회)`, 최대 < 기대 * 1.4);
  참(`번호 사이 차이가 크지 않다 (최대−최소 = ${최대 - 최소})`, 최대 - 최소 < 기대 * 0.7);
}

묶음('이력 준비가 결과를 바꾸지 않는가');
{
  // 빠르게 하려고 이력을 미리 풀어 두었다. 그 최적화가 답을 바꾸면 안 된다.
  const 이력 = [
    { 열, 행, 배치: 차례대로 },
    { 열, 행, 배치: 앉히기(섞기(번호들), 열, 행, []) },
  ];
  const 후보 = 앉히기(섞기(번호들), 열, 행, []);
  const 준비된 = 이력준비(이력);
  확인('미리 푼 이력의 개수가 같다', 준비된.length, 이력.length);
  확인('가장 최근 이력의 무게가 1', 준비된[0].무게, 1);
  확인('그 다음 이력의 무게가 1/2', 준비된[1].무게, 0.5);
  참('짝 집합이 원본과 맞는다',
    준비된[0].짝.size === new Set(짝목록(차례대로, 열, 행).map(짝열쇠)).size);
  참('벌점이 0 이상이다', 벌점(후보, 열, 행, 이력) >= 0);
}
