// XML 이 짝이 맞는지 — 여는 태그와 닫는 태그를 쌓아 가며 본다
function 짝맞나(xml) {
  const 몸 = xml.replace(/^<\?xml[^>]*\?>/, '');
  const 쌓기 = [];
  for (const [, 닫음, 이름, , 혼자] of 몸.matchAll(/<(\/?)([\w:]+)([^>]*?)(\/?)>/g)) {
    if (혼자) continue;
    if (닫음) { if (쌓기.pop() !== 이름) return false; } else 쌓기.push(이름);
  }
  const 글만 = 몸.replace(/<[^>]*>/g, '');
  return 쌓기.length === 0 && !/[<>]/.test(글만) && !/&(?!amp;|lt;|gt;|quot;|apos;)/.test(글만);
}

