import { 행열, 자리이름, 구역, 쓰는자리, 짝목록, 짝열쇠, 구역표, 앉히기 } from '../src/core/seats.js';
import { 묶음, 확인, 참 } from './harness.mjs';

묶음('자리 번호 ↔ 행·열');
확인('0번은 1행 1열', 행열(0, 5), { 행: 0, 열: 0 });
확인('5번은 2행 1열', 행열(5, 5), { 행: 1, 열: 0 });
확인('29번은 6행 5열', 행열(29, 5), { 행: 5, 열: 4 });
확인('사람이 읽는 이름', 자리이름(7, 5), '2행 3열');

묶음('앞·중·뒤 구역');
확인('6행이면 둘씩 나뉜다', [0, 1, 2, 3, 4, 5].map((r) => 구역(r, 6)), ['앞', '앞', '중', '중', '뒤', '뒤']);
확인('3행이면 하나씩', [0, 1, 2].map((r) => 구역(r, 3)), ['앞', '중', '뒤']);
확인('1행이면 모두 앞', [구역(0, 1)], ['앞']);
확인('2행이면 앞과 뒤', [구역(0, 2), 구역(1, 2)], ['앞', '뒤']);
참('마지막 행은 언제나 뒤', [4, 5, 6, 7, 8, 9, 10].every((행) => 구역(행 - 1, 행) === '뒤'));
참('첫 행은 언제나 앞', [3, 4, 5, 6, 7, 8, 9, 10].every((행) => 구역(0, 행) === '앞'));

묶음('없는 자리 빼기');
확인('아무것도 안 빼면 다 쓴다', 쓰는자리(3, 2, []), [0, 1, 2, 3, 4, 5]);
확인('두 자리를 빼면 넷', 쓰는자리(3, 2, [1, 4]), [0, 2, 3, 5]);
확인('없는 자리는 null 로 남는다', 앉히기([1, 2, 3, 4], 3, 2, [1, 4]), [1, null, 2, 3, null, 4]);

묶음('짝(좌우로 붙어 앉은 사람) 찾기');
const 배치 = 앉히기([1, 2, 3, 4, 5, 6], 3, 2, []);
확인('3열 2행이면 짝이 네 쌍', 짝목록(배치, 3, 2), [[1, 2], [2, 3], [4, 5], [5, 6]]);
참('줄이 다르면 짝이 아니다', !짝목록(배치, 3, 2).some(([a, b]) => a === 3 && b === 4));
// ★ 가운데가 비면 실제로 떨어져 앉으므로 짝으로 보면 안 된다
const 빈칸섞임 = 앉히기([1, 2, 3, 4, 5], 3, 2, [1]);
확인('가운데가 빈 자리면 짝이 아니다', 짝목록(빈칸섞임, 3, 2), [[3, 4], [4, 5]]);
확인('짝 열쇠는 받은 차례대로 잇는다 (정렬은 짝목록이 맡는다)', 짝열쇠([2, 9]), '2-9');
확인('5열 6행 30자리의 짝은 24쌍', 짝목록(앉히기([...Array(30).keys()].map((n) => n + 1), 5, 6, []), 5, 6).length, 24);

묶음('번호별 구역표');
const 표 = 구역표(앉히기([...Array(30).keys()].map((n) => n + 1), 5, 6, []), 5, 6);
확인('1번은 맨 앞줄', 표[1], '앞');
확인('30번은 맨 뒷줄', 표[30], '뒤');
확인('15번은 가운데', 표[15], '중');
확인('30명 모두 구역이 있다', Object.keys(표).length, 30);
